-- ====================================================================
-- KHETMITRA SMART CROP PROTECTION SYSTEM — DATABASE SCHEMA
-- ====================================================================
-- This SQL script sets up the tables, policies, and realtime streams
-- for KhetMitra on Supabase. Execute in the Supabase SQL Editor.

-- Enable UUID extension
create extension if not exists "uuid-ossp";

-- 1. Field Detection Alerts Table
create table if not exists public.field_alerts (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    side text not null check (side in ('North', 'East', 'South', 'West')),
    sensor_id text not null,
    animal text not null,
    threat_level text default 'Medium' check (threat_level in ('Low', 'Medium', 'High')),
    severity text default 'medium' check (severity in ('low', 'medium', 'high')),
    status text default 'New' check (status in ('New', 'Reviewed', 'Resolved')),
    deterrent_action text,
    deterrent_success boolean default true,
    notes text,
    user_id uuid references auth.users(id) on delete cascade
);

-- 2. ESP32 Device Telemetry Table
create table if not exists public.device_telemetry (
    id bigint generated by default as identity primary key,
    device_id text not null default 'ESP32_CENTRAL_01',
    recorded_at timestamp with time zone default timezone('utc'::text, now()) not null,
    status text default 'online' check (status in ('online', 'offline', 'standby')),
    battery_voltage numeric(4, 2) default 4.15,
    solar_current_ma integer default 380,
    core_temp_c numeric(4, 1) default 38.2,
    free_heap_bytes integer default 188416,
    wifi_rssi_dbm integer default -64,
    firmware_version text default 'v1.2.0-khetmitra',
    operating_mode text default 'ARMED' check (operating_mode in ('ARMED', 'ALERT', 'DISARMED')),
    buzzer_active boolean default false,
    light_active boolean default false,
    auto_protection boolean default true
);

-- 3. Farmer Profiles Table
create table if not exists public.farmer_profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    updated_at timestamp with time zone default timezone('utc'::text, now()) not null,
    farm_name text default 'Green Valley Agricultural Plots',
    farm_area text default '5.5 Acres',
    primary_crops text default 'Wheat, Mustard, Seasonal Vegetables',
    location text default 'Northern Canal Boundary',
    developer_name text default 'App Developer',
    developer_bio text default 'Lead Full-Stack & IoT Developer',
    profile_photo text,
    linkedin_url text,
    instagram_url text,
    github_url text
);

-- 4. Enable Row Level Security (RLS)
alter table public.field_alerts enable row level security;
alter table public.device_telemetry enable row level security;
alter table public.farmer_profiles enable row level security;

-- 5. Policies for Public / Authenticated Access
-- Field Alerts
create policy "Allow authenticated users to read alerts"
    on public.field_alerts for select
    to authenticated, anon
    using (true);

create policy "Allow inserts to field_alerts"
    on public.field_alerts for insert
    to authenticated, anon
    with check (true);

create policy "Allow updates to field_alerts"
    on public.field_alerts for update
    to authenticated, anon
    using (true);

-- Device Telemetry
create policy "Allow read access to device_telemetry"
    on public.device_telemetry for select
    to authenticated, anon
    using (true);

create policy "Allow insert/update to device_telemetry"
    on public.device_telemetry for insert
    to authenticated, anon
    with check (true);

-- Farmer Profiles
create policy "Users can view their own profile"
    on public.farmer_profiles for select
    to authenticated
    using (auth.uid() = id);

create policy "Users can update their own profile"
    on public.farmer_profiles for update
    to authenticated
    using (auth.uid() = id);

create policy "Users can insert their own profile"
    on public.farmer_profiles for insert
    to authenticated
    with check (auth.uid() = id);

-- 6. Realtime Replication Publication
-- Add tables to the supabase_realtime publication for live streaming
alter publication supabase_realtime add table public.field_alerts;
alter publication supabase_realtime add table public.device_telemetry;

